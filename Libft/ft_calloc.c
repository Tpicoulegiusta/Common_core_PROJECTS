#include "libft.h"

void	*ft_calloc(size_t count, size_t size)
{
	char		*str;
	size_t		x;

	x = 0;
	if (size && SIZE_MAX / size < count)
		return (NULL);
	str = malloc(size * count);
	if (!str)
		return (NULL);
	while (x < count * size)
	{
		str[x] = 0;
		x++;
	}
	return (str);
}
